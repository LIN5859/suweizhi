document.querySelectorAll("[data-save]").forEach((btn) => {
  const saved = JSON.parse(localStorage.getItem("suwei-saved") || "[]");
  if (saved.includes(btn.dataset.save)) {
    btn.classList.add("saved");
    btn.textContent = "♥";
  }
  btn.addEventListener("click", (e) => {
    e.preventDefault();
    let list = JSON.parse(localStorage.getItem("suwei-saved") || "[]");
    const name = btn.dataset.save;
    if (list.includes(name)) {
      list = list.filter((x) => x !== name);
      btn.classList.remove("saved");
      btn.textContent = "♡";
      notify(`已取消收藏「${name}」`);
    } else {
      list.push(name);
      btn.classList.add("saved");
      btn.textContent = "♥";
      notify(`已收藏「${name}」`);
    }
    localStorage.setItem("suwei-saved", JSON.stringify(list));
  });
});
