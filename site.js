function renderEssay(data) {
  const paragraphs = data.paragraphs
    .map((paragraph, index) => {
      if (index === 0) return `<p class="dropcap">${paragraph}</p>`;
      if (index === 1) {
        return `<p class="pullquote">“${paragraph.slice(0, 24)}……”</p><p>${paragraph}</p>`;
      }
      return `<p>${paragraph}</p>`;
    })
    .join("");

  return `
    <article class="essay reveal">
      <p class="eyebrow">EDITORIAL</p>
      <h2>${data.heading}</h2>
      ${paragraphs}
      <table class="info-table">
        <tr><th>网站主题</th><td>苏州地方美食文化</td></tr>
        <tr><th>视觉关键词</th><td>江南、时令、园林、烟火</td></tr>
        <tr><th>浏览方式</th><td>顶部导航与页面内链接</td></tr>
      </table>
    </article>`;
}

